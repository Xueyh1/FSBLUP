"""Paired release measurements. Run from cpp in a Slurm allocation."""

import argparse
import csv
import itertools
import json
import os
import shutil
import statistics
import subprocess
import time
from pathlib import Path

from pcg_scale import generate


def read(path):
    if not path.exists():
        return []
    with path.open() as f:
        return list(csv.DictReader(f, delimiter="\t"))


def write(path, rows):
    with path.open("w") as f:
        w = csv.DictWriter(f, rows[0], delimiter="\t", lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def cores():
    result = {}
    for i in sorted(os.sched_getaffinity(0)):
        t = Path(f"/sys/devices/system/cpu/cpu{i}/topology")
        key = tuple((t / x).read_text() for x in ("physical_package_id", "core_id"))
        result.setdefault(key, i)
    return list(result.values())


def execute(root, label, exe, args, threads, description):
    out = root / label
    cpus = cores()
    assert len(cpus) >= threads, cpus
    cmd = [
        "taskset",
        "-c",
        ",".join(str(c) for c in cpus[:threads]),
        exe,
        *args,
        "--threads",
        threads,
        "--log-level",
        "off",
        "--out",
        out,
    ]
    with (root / "commands.jsonl").open("a") as f:
        print(json.dumps(list(map(str, cmd))), file=f)
    start = time.monotonic()
    p = subprocess.run(list(map(str, cmd)), capture_output=True, text=True)
    elapsed = time.monotonic() - start
    rt = (read(out / "runtime.tsv") or [{}])[0]
    usage = (read(out / "cache_usage.tsv") or [{}])[0]
    tune = (read(out / "tuning.tsv") or [{}])[0]
    fits = read(out / "cv_pcg_summary.tsv") + read(out / "pcg_summary.tsv")
    search = read(out / "search.tsv")
    return dict(
        **description,
        threads=threads,
        wall_s=elapsed,
        exit=p.returncode,
        workers=rt.get("weight_workers", "NA"),
        rss_KiB=rt.get("peak_rss_kib", "NA"),
        rhs=sum(int(a["rhs"]) for a in fits),
        matvec=sum(int(a["matvec"]) for a in fits),
        probes=sum(int(a["probes"]) for a in fits),
        feature_B=usage.get("feature_bytes", "NA"),
        verified_B=usage.get("verified_cache_bytes", "NA"),
        calibration_B=usage.get("calibration_bytes", "NA"),
        preload_B=usage.get("training_preload_bytes", "NA"),
        training_B=usage.get("training_bytes", "NA"),
        cross_B=usage.get("cross_bytes", "NA"),
        points=len(search),
        scored=sum(r["valid"] == "1" for r in search),
        completed=sum(
            sum(k.startswith("r1f") and v not in ("NA", "nan") for k, v in r.items())
            for r in search
        ),
        alpha=tune.get("selected_alpha", "NA"),
        beta=tune.get("selected_beta", "NA"),
        retry_reserved=tune.get("retry_reserved", "NA"),
        reason=p.stderr.strip().splitlines()[-1] if p.returncode else "",
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("old", type=Path)
    parser.add_argument("new", type=Path)
    parser.add_argument(
        "small", type=Path, help="stream fixture generated by reproduce_operators.py"
    )
    parser.add_argument("output", type=Path)
    opt = parser.parse_args()
    root = opt.output
    root.mkdir()
    medium = root / "medium"
    generate(medium, 320, 256, 16, False)
    exe = opt.old.resolve()
    subprocess.run(
        [
            exe,
            "prepare",
            "--ped",
            medium / "ped.tsv",
            "--snp",
            medium / "snp.tsv",
            "--omics",
            medium / "omics.tsv",
            "--snp-format",
            "2bit",
            "--out",
            medium / "cache",
            "--log-level",
            "off",
        ],
        check=True,
    )
    result = []
    seeds = []
    for case, d, pheno, folds in [
        ("small", opt.small, "pheno", "folds"),
        ("medium", medium, "large.tsv", "large-folds.tsv"),
    ]:
        common = [
            "fit",
            "--cache",
            d / "cache",
            "--cache-backend",
            "operator",
            "--cache-storage",
            "stream",
            "--pheno",
            d / pheno,
            "--trait",
            "trait",
            "--folds-file",
            d / folds,
            "--metric",
            "rmse",
            "--strict-simplex",
            "--parallel",
            "weights",
            "--memory-mb",
            1024,
        ]
        for rep in range(4):
            for threads in (1, 2, 4, 8) if rep % 2 == 0 else (8, 4, 2, 1):
                for version, exe in (
                    [("old", opt.old), ("new", opt.new)]
                    if rep % 2 == 0
                    else [("new", opt.new), ("old", opt.old)]
                ):
                    label = f"{case}-{version}-{threads}-{rep}"
                    args = common + ["--varcomp", "fixed", "--lambda", 1]
                    if version == "new":
                        args += ["--score-policy", "legacy"]
                    r = execute(
                        root,
                        label,
                        exe.resolve(),
                        args,
                        threads,
                        dict(case=case, version=version, rep=rep),
                    )
                    assert r["exit"] == 0, r
                    if rep:
                        result.append(r)
        write(root / "replicates.tsv", result)
        if case == "medium":
            for seed, budget in itertools.product((19, 42), (0, 256)):
                label = f"retry-{seed}-{budget}"
                args = common + [
                    "--trace",
                    "hutchinson",
                    "--varcomp",
                    "ai-reml",
                    "--trace-rank",
                    4,
                    "--probe-seed",
                    seed,
                    "--probes",
                    4,
                    "--max-probes",
                    8,
                    "--retry-probes",
                    budget,
                    "--mc-tol",
                    ".15",
                    "--probe-solver",
                    "lanczos",
                    "--slq-depth",
                    32,
                    "--slq-reorth",
                    "local",
                    "--slq-batch",
                    4,
                ]
                r = execute(
                    root,
                    label,
                    opt.new.resolve(),
                    args,
                    2,
                    dict(case=case, seed=seed, budget=budget),
                )
                seeds.append(r)
                write(root / "sensitivity.tsv", seeds)
    medians = []
    for key, group in itertools.groupby(
        sorted(result, key=lambda r: (r["case"], r["version"], r["threads"])),
        key=lambda r: (r["case"], r["version"], r["threads"]),
    ):
        group = list(group)
        r = group[0].copy()
        r.pop("rep")
        for field in ("wall_s", "rss_KiB"):
            values = [float(g[field]) for g in group]
            r[field] = statistics.median(values)
            r[field + "_MAD"] = statistics.median(abs(v - r[field]) for v in values)
        medians.append(r)
    write(root / "medians.tsv", medians)


if __name__ == "__main__":
    main()
