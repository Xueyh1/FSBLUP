"""Exercise whether training-only scoring labels affect a held-out temporal search.

The replays change only an auxiliary column on training individuals. All fitted
phenotypes, fixed design, kernels, time labels and validation targets are identical.
The exact validation target is generated by a dense fixed-ratio BLUP.
"""
import argparse
import csv
import os
from pathlib import Path
import subprocess

import numpy as np


def write_tsv(path, columns, rows):
    with path.open("w", newline="") as output:
        writer = csv.writer(output, delimiter="\t", lineterminator="\n")
        writer.writerow(columns)
        writer.writerows(rows)


def read_tsv(path):
    with path.open() as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def predict(k, y, train, valid):
    covariance = k[np.ix_(train, train)] + np.eye(len(train))
    q = np.linalg.solve(covariance, np.column_stack((y[train], np.ones(len(train)))))
    residual = q[:, 0] - q[:, 1] * (q[:, 0].sum() / q[:, 1].sum())
    return k[np.ix_(valid, train)] @ residual


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("binary", type=Path)
    parser.add_argument("out", type=Path)
    args = parser.parse_args()
    binary, out = args.binary.resolve(), args.out.resolve()
    out.mkdir(parents=True, exist_ok=False)
    rng = np.random.default_rng(178)
    n, m = 40, 64
    ids = [f"i{i:03}" for i in range(n)]
    x, z = rng.normal(size=(2, n, m))
    kernels = {"A": np.eye(n), "G": x @ x.T / m, "O": z @ z.T / m}
    for name, matrix in kernels.items():
        write_tsv(out / (name + ".tsv"), ["ID", *ids], zip(ids, *matrix.T))
    train, valid = np.arange(24), np.arange(24, n)
    y = rng.normal(size=n)
    years = np.where(np.arange(n) < 24, 2019, 2021)
    alpha, beta = .34375, .34375
    k = ((1 - alpha - beta + 1e-6) * kernels["A"]
         + beta * kernels["G"] + alpha * kernels["O"])
    validation_target = predict(k, y, train, valid)
    target = np.empty(n)
    target[valid] = validation_target
    rows = []
    scores = {}
    for training_only_label in (0., 400.):
        target[train] = training_only_label
        augmented = out / f"pheno_{int(training_only_label)}.tsv"
        write_tsv(augmented, ["ID", "trait", "target", "year"],
                  zip(ids, y, target, years))
        for solver in ("direct", "pcg"):
            dest = out / f"{solver}_{int(training_only_label)}"
            cmd = [binary, "fit", "--pheno", augmented, "--trait", "trait",
                   "--score-col", "target", "--metric", "rmse", "--year", "2020",
                   "--strict-simplex", "--solver", solver, "--varcomp", "fixed",
                   "--lambda", "1", "--log-level", "error", "--out", dest]
            for name in kernels:
                cmd.extend(["--" + name, out / (name + ".tsv")])
            subprocess.run(cmd, env=dict(os.environ, OPENBLAS_NUM_THREADS="1"),
                           check=True)
            summary = read_tsv(dest / "tuning.tsv")[0]
            cases = read_tsv(dest / "search.tsv")
            scores[solver, training_only_label] = {
                (float(line["alpha"]), float(line["beta"])): float(line["mean"])
                for line in cases}
            rows.append([solver, training_only_label, summary["score_scale"],
                         len(cases), summary["selected_alpha"], summary["selected_beta"],
                         summary["selection_score"], summary["scorable_folds_per_point"]])
    output = out / "observed.tsv"
    write_tsv(output, ["solver", "training_only_score", "score_scale", "visited",
                       "selected_alpha", "selected_beta", "RMSE", "scorable_folds"], rows)
    for solver in ("direct", "pcg"):
        left, right = scores[solver, 0.], scores[solver, 400.]
        common = set(left) & set(right)
        print(solver, "common points", len(common), "max common score difference",
              max(abs(left[p] - right[p]) for p in common))
    print(output.read_text(), end="")

    # All simplex fusions are positive definite. AUC cannot be scored when
    # only one label occurs in the validation set. Inspect the failure type.
    auc_labels = np.zeros(n, dtype=int)
    auc_labels[train] = np.arange(len(train)) % 2
    auc_input = out / "auc_single_class.tsv"
    write_tsv(auc_input, ["ID", "trait", "binary_target", "year"],
              zip(ids, y, auc_labels, years))
    auc_out = out / "auc_single_class"
    cmd = [binary, "fit", "--pheno", auc_input, "--trait", "trait",
           "--score-col", "binary_target", "--metric", "auc", "--year", "2020",
           "--strict-simplex", "--solver", "direct", "--varcomp", "fixed",
           "--lambda", "1", "--log-level", "error", "--out", auc_out]
    for name in kernels:
        cmd.extend(["--" + name, out / (name + ".tsv")])
    completed = subprocess.run(cmd, env=dict(os.environ, OPENBLAS_NUM_THREADS="1"),
                               text=True, capture_output=True)
    (out / "auc.stderr").write_text(completed.stderr)
    print("Single-class AUC exit", completed.returncode)
    if (auc_out / "tuning.tsv").exists():
        summary = read_tsv(auc_out / "tuning.tsv")[0]
        for name in ("scorable_folds_per_point", "fold_attempts", "candidates_visited",
                     "invalid_kernel"):
            print(name, summary[name])


if __name__ == "__main__":
    main()
